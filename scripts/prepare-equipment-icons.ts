import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const collection = resolve(root, "../FitCoach_60_Approved_Collection_v4_SVG");
const manifest = JSON.parse(await readFile(resolve(collection, "manifest.json"), "utf8")) as { items: { code: string; name_ru: string; available_svg_file: string | null }[] };
const assets = resolve(root, "apps/mobile/assets/equipment");
await mkdir(assets, { recursive: true });
const glyphs: Record<string, string> = {};
for (const item of manifest.items) {
  if (!item.available_svg_file) continue;
  const source = resolve(collection, item.available_svg_file);
  const svg = await readFile(source, "utf8");
  if (!/<svg\b/u.test(svg) || !/viewBox="[\d. ]+"/u.test(svg) || !/<path\b/u.test(svg) || /<(?:script|image|foreignObject)\b|base64|\bhref\s*=/iu.test(svg)) throw new Error(`Invalid vector asset: ${item.code}`);
  await copyFile(source, resolve(assets, `${item.code}.svg`));
  glyphs[item.code] = svg.replace(/<!--[\s\S]*?-->|<title>[\s\S]*?<\/title>/gu, "").replace(/\s(?:role|aria-label)="[^"]*"/gu, "").replace(/\s+/gu, " ").trim();
}
await writeFile(resolve(root, "apps/mobile/src/features/exercises/presentation/approvedEquipmentGlyphs.generated.ts"),
  `// Owner-supplied approved vectors. Generated by scripts/prepare-equipment-icons.ts.\nexport const approvedEquipmentGlyphs: Readonly<Record<string, string>> = ${JSON.stringify(glyphs, null, 2)};\n`, "utf8");
console.log(`Prepared ${Object.keys(glyphs).length} approved SVG equipment icons; missing originals keep the existing glyphs.`);
